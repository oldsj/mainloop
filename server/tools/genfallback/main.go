// Command genfallback reads the strict server interface from the oapi-codegen output and writes
// a type whose every method answers 501, so a domain slice replaces one operation set at a time.
// Run by go generate from internal/api.
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"log"
	"os"
	"sort"
)

func main() {
	if len(os.Args) != 3 {
		log.Fatal("usage: genfallback <api.gen.go> <unimplemented.gen.go>")
	}
	methods, err := strictMethods(os.Args[1])
	if err != nil {
		log.Fatal(err)
	}
	var buf bytes.Buffer
	buf.WriteString(`// Code generated by tools/genfallback; DO NOT EDIT.

package api

import (
	"context"

	"github.com/oldsj/mainloop/server/internal/apierr"
)

// Unimplemented answers 501 to every operation in the contract. Embed it below the per-domain
// handlers so that an operation a domain has not implemented yet still has an answer.
type Unimplemented struct{}

var _ StrictServerInterface = Unimplemented{}
`)
	for _, m := range methods {
		fmt.Fprintf(&buf, "\n// %s is not implemented yet.\nfunc (Unimplemented) %s(context.Context, %sRequestObject) (%sResponseObject, error) {\n\treturn nil, apierr.NotImplemented\n}\n", m, m, m, m)
	}
	src, err := format.Source(buf.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(os.Args[2], src, 0o644); err != nil { //nolint:gosec // generated source file
		log.Fatal(err)
	}
}

func strictMethods(path string) ([]string, error) {
	file, err := parser.ParseFile(token.NewFileSet(), path, nil, 0)
	if err != nil {
		return nil, err
	}
	var names []string
	for _, decl := range file.Decls {
		gen, ok := decl.(*ast.GenDecl)
		if !ok {
			continue
		}
		for _, spec := range gen.Specs {
			ts, ok := spec.(*ast.TypeSpec)
			if !ok || ts.Name.Name != "StrictServerInterface" {
				continue
			}
			iface, ok := ts.Type.(*ast.InterfaceType)
			if !ok {
				return nil, fmt.Errorf("StrictServerInterface is not an interface")
			}
			for _, m := range iface.Methods.List {
				for _, n := range m.Names {
					names = append(names, n.Name)
				}
			}
		}
	}
	if len(names) == 0 {
		return nil, fmt.Errorf("no StrictServerInterface in %s", path)
	}
	sort.Strings(names)
	return names, nil
}
