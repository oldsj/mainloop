#!/usr/bin/env bash
# Regenerates the Swift API client (ios/Packages/MainloopKit/Sources/MainloopAPI/Generated) from
# api/openapi.yaml with the pinned swift-openapi-generator, filtered to the operations in
# ios/Packages/APIGen/openapi-generator-config.yaml. The output is committed; CI reruns this and
# fails if it changes anything, the same rule as `go generate` and web's schema.gen.ts.
#
# The generator reads a temporary copy of the contract rewritten by PrepareContract
# (ios/Packages/APIGen/Sources/PrepareContract/main.swift): nullable `anyOf: [X, null]` becomes an
# optional X, and integer bounds beyond Int64 are dropped. api/openapi.yaml itself never changes.
set -euo pipefail

cd "$(dirname "$0")/.."
root=$(cd .. && pwd)
out=Packages/MainloopKit/Sources/MainloopAPI/Generated
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

swift build --package-path Packages/APIGen -c release --product swift-openapi-generator >/dev/null
swift build --package-path Packages/APIGen -c release --product PrepareContract >/dev/null
bin=$(swift build --package-path Packages/APIGen -c release --show-bin-path)
gen=${bin}/swift-openapi-generator

"${bin}/PrepareContract" "${root}/api/openapi.yaml" "${tmp}/openapi.yaml"

rm -rf "${tmp}/out" && mkdir "${tmp}/out"
"${gen}" generate "${tmp}/openapi.yaml" \
  --config Packages/APIGen/openapi-generator-config.yaml \
  --output-directory "${tmp}/out"

rm -rf "${out}" && mkdir -p "${out}"
for f in "${tmp}"/out/*.swift; do
  {
    echo "// Generated by ios/scripts/generate-api.sh from api/openapi.yaml. Do not edit."
    cat "${f}"
  } >"${out}/$(basename "${f}")"
done
files=$(find "${out}" -name '*.swift')
echo "Wrote ${out}:"
echo "${files}"
